SYSTEM_SETUP_USER="$SYSTEM_USER"

SYSTEM_TMP=/tmp
SYSTEM_SHM=/dev/shm
SYSTEM_LOG=/var/log
SYSTEM_CACHE=/var/cache
SYSTEM_COREDUMP=/var/lib/systemd/coredump
