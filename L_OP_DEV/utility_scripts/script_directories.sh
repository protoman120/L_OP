#OS
OS_ANALYSIS=$SCRIPT_SOFTWARE_SCRIPTS/os_analysis.sh
#KERNEL
KERNEL_OPTIMIZATIONS=$SCRIPT_SOFTWARE_SCRIPTS/kernel_optimizations.sh
