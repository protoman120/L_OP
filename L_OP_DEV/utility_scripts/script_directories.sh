RAM_OPTIMIZATIONS=$SCRIPT_HARDWARE_SCRIPTS/ram_optimizations.sh
#STORAGE
STORAGE_ANALYSIS=$SCRIPT_HARDWARE_SCRIPTS/storage_analysis.sh
